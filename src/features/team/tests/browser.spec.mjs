// Run against an isolated test backend: this creates an account and saved forecasts.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.MULA_PLAYWRIGHT_MODULE || "playwright");
const baseURL = process.env.MULA_TEST_URL || "http://127.0.0.1:3001";
const browser = await chromium.launch({ headless: true, executablePath: process.env.MULA_BROWSER_PATH });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const signup = await page.request.post(baseURL + "/api/auth/signup", { data: { username: `teamcheck_${Date.now()}`, password: "test-only-password-123" } });
  assert.equal(signup.status(), 201);
  await page.goto(baseURL + "/team");
  await page.getByRole("heading", { name: "Your people, powered by Mula." }).waitFor();
  assert.equal(await page.locator(".agent-card").count(), 2);
  assert.equal(await page.getByRole("button", { name: /Configure Inventory|Configure Procurement/ }).count(), 0);
  const background = await page.locator(".team-shell").evaluate((node) => getComputedStyle(node).backgroundColor);
  assert.equal(background, "rgb(17, 18, 20)");
  await page.getByLabel("Instructions", { exact: true }).fill("Reply briefly in English.");
  await page.getByLabel("Reference data", { exact: true }).fill("We operate a coffee shop. Sales values are in IDR.");
  await page.getByRole("button", { name: "Save settings", exact: true }).click();
  await page.getByText("Saved for your account. Applies to the next request.").waitFor();
  await page.reload();
  await page.getByLabel("Instructions", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Instructions", { exact: true }).inputValue(), "Reply briefly in English.");
  await page.screenshot({ path: "/tmp/mula-team-settings-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Configure Forecasting", exact: true }).click();
  await page.getByLabel("Instructions", { exact: true }).fill("Explain in three short sentences, in English.");
  await page.getByRole("button", { name: "Save settings", exact: true }).click();
  await page.getByText("Saved for your account. Applies to the next request.").waitFor();
  await page.getByRole("button", { name: "Run a forecast", exact: true }).click();
  const upload = page.getByLabel("Upload historical data");
  await upload.waitFor();
  await page.waitForFunction(() => !document.querySelector('input[type="file"]').disabled);
  const csv = "date,sales\n" + Array.from({ length: 30 }, (_, index) => `2026-01-${String(index + 1).padStart(2, "0")},${100 + index * 10}`).join("\n");
  await upload.setInputFiles({ name: "sales.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await page.getByText(/CSV: sales.csv/).waitFor();
  await page.getByRole("button", { name: "Run forecast", exact: true }).click();
  await page.getByRole("heading", { name: "sales · Trend (drift)" }).waitFor();
  const table = page.getByRole("table", { name: "Forecast values" });
  assert.match(await table.innerText(), /2026-01-31\s+400/);
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download forecast CSV ↓" }).click();
  assert.equal((await downloadPromise).suggestedFilename(), "mula-forecast.csv");
  if (process.env.MULA_TEST_EXPLANATION === "1") {
    await page.getByRole("button", { name: "Ask Forecasting to explain" }).click();
    await page.getByLabel("Forecasting explanation").waitFor({ timeout: 180000 });
    assert.ok((await page.getByLabel("Forecasting explanation").innerText()).length > 20);
  }
  await page.screenshot({ path: "/tmp/mula-forecast-desktop.png", fullPage: true });
  await page.reload();
  await page.getByRole("button", { name: "Configure Forecasting", exact: true }).click();
  await page.getByRole("button", { name: "Run a forecast", exact: true }).click();
  await page.getByRole("heading", { name: "sales · Trend (drift)" }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/mula-team-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole("button", { name: "Configuration", exact: true }).click();
  await page.getByLabel("Last value", { exact: true }).uncheck();
  await page.getByRole("button", { name: "Run a forecast", exact: true }).click();
  await page.getByText("Save your configuration changes before running a forecast.").waitFor();
  assert.equal(await page.getByRole("button", { name: "Run forecast", exact: true }).isDisabled(), true);
  assert.deepEqual(errors, []);
  console.log("Team settings persistence, real forecast, export, saved report, tool edits and responsive layout passed.");
} finally { await browser.close(); }
