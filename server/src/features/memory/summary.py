"""MEMORY.md: a short, regenerated summary of the store, never edited by the agent.

The file mirrors the runtime's own memory layout (a business section and an owner
section with the same size limits), but Mula writes it from the store after every
change. It exists for the owner to read and for the system prompt; the store is the
source of truth.
"""
import os
from pathlib import Path
import tempfile

from fastapi import HTTPException

from . import store

# The runtime's own limits for MEMORY.md and USER.md, so the summary never outgrows
# what a built-in memory would have supplied.
LIMITS = {"business": 2200, "owner": 1375}
HEADINGS = {"business": "About the business", "owner": "About the owner"}
HEADER = ("# Mula memory\n\n"
          "Written by Mula from the memory store. Do not edit this file: correct or retire a memory "
          "on the Memory page, or ask the Operator to remember the new version.\n")


def section(target, entries):
    kept = [entry for entry in entries if entry["target"] == target]
    lines = []
    used = 0
    shown = 0
    for entry in kept:
        line = f"- [{entry['id']}] {entry['fact']} ({entry['created_at'][:10]})"
        if used + len(line) + 1 > LIMITS[target]:
            break
        lines.append(line)
        used += len(line) + 1
        shown += 1
    if shown < len(kept):
        lines.append(f"- {len(kept) - shown} more in Memory")
    if not lines:
        lines.append("- Nothing saved yet.")
    return f"\n## {HEADINGS[target]}\n\n" + "\n".join(lines) + "\n"


def render(entries):
    """Deterministic text for the active entries, newest first within each section."""
    ordered = sorted(entries, key=lambda entry: entry["id"], reverse=True)
    return HEADER + section("business", ordered) + section("owner", ordered)


def summary_path(account_id):
    return store.memory_folder(account_id) / "MEMORY.md"


def regenerate(account_id, entries):
    text = render(entries)
    path = summary_path(account_id)
    if path.is_symlink():
        raise HTTPException(409, "The memory summary must not be a symbolic link.")
    try:
        descriptor, temporary = tempfile.mkstemp(prefix=".MEMORY-", dir=path.parent)
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8") as output:
                output.write(text)
                output.flush()
                os.fsync(output.fileno())
            os.chmod(temporary, 0o600)
            os.replace(temporary, path)
        finally:
            Path(temporary).unlink(missing_ok=True)
    except OSError as error:
        raise HTTPException(503, "The memory summary could not be written. Check the runtime folder's permissions.") from error
    return text


def current(account_id):
    """The summary for the store as it is now. Always regenerated, so a hand edit never leaks into a prompt."""
    with store.open_store(account_id) as db:
        entries = store.active_entries(db)
    return regenerate(account_id, entries)
