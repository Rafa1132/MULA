"""One Mula runtime profile per account, so runtime state is never shared between owners.

The runtime serves every named profile under `<HERMES_HOME>/profiles/` when its root
config has `gateway.multiplex_profiles: true`. Requests reach a profile through the
URL prefix `/p/<profile>/v1/...` and must carry that profile's own `API_SERVER_KEY`;
the root key never opens another profile. Each profile runs in its own scope: its own
config, its own runtime sessions, and secrets from its own `.env` only.

Profile names and keys are derived from the account id and a server-side seed, so
nothing about a profile is stored per account and nothing secret is logged. The
runtime's built-in memory stays off in every profile: Mula's own memory store
(features/memory) is what the agents remember with.
"""
import hashlib
import hmac
import os
from pathlib import Path
import re
import tempfile
from uuid import UUID

from . import runtime_control
from .config import HERMES_HOME, MULA_PROFILE_KEY_SEED
from .paths import PROJECT_ROOT

BACKEND = PROJECT_ROOT / "server"
TEMPLATE = BACKEND / "hermes" / "profile.config.yaml"
# The identity line the runtime puts first in every system prompt. Without it the runtime seeds
# its own coding-agent identity, which on the small local model outweighs the agent's Mula role
# and the owner's instructions that follow. The runtime keeps an existing SOUL.md as it is.
IDENTITY = BACKEND / "hermes" / "SOUL.md"
RUNTIME_HOME = PROJECT_ROOT / ".runtime" / "hermes"
if HERMES_HOME:
    RUNTIME_HOME = Path(HERMES_HOME)
KEY_SEED = MULA_PROFILE_KEY_SEED
# Secrets every account profile needs from the root profile's .env: a named profile
# reads only its own file, never the root's or the process environment.
MIRRORED_SECRETS = ("MULA_TOOLS_KEY", "ANTHROPIC_API_KEY")
# The model address every profile config reads as ${MULA_MODEL_BASE_URL}. Not a secret, but a
# profile only sees its own .env, so it is copied too. Order: backend environment, then the
# root profile's .env, then local Ollama, so a missing value never leaves a literal placeholder.
MODEL_BASE_URL_NAME = "MULA_MODEL_BASE_URL"
DEFAULT_MODEL_BASE_URL = "http://127.0.0.1:11434/v1"
# The runtime's own grammar for profile ids (hermes_constants.PROFILE_ID_RE at the pinned revision).
PROFILE_ID = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")
NO_SKILLS_MARKER = ".no-bundled-skills"
# How long a turn waits for a gateway that has acknowledged a new profile but is still bringing it up.
SERVE_WAIT_SECONDS = 12.0


class ProfileError(RuntimeError):
    """The account's runtime profile cannot be provided; the message is safe to show."""


def configured() -> bool:
    return bool(KEY_SEED)


def profile_name(account_id: str) -> str:
    # Account ids are UUIDs, so the name is a valid profile id and unique per account.
    name = "mula-" + UUID(account_id).hex
    if not PROFILE_ID.match(name):
        raise ProfileError("The account id cannot name a runtime profile.")
    return name


def profile_key(account_id: str) -> str:
    """The profile's API_SERVER_KEY, derived rather than stored."""
    if not configured():
        raise ProfileError("Mula's runtime profiles are not set up. Run the backend's runtime setup first.")
    digest = hmac.new(KEY_SEED.encode("utf-8"), str(UUID(account_id)).encode("utf-8"), hashlib.sha256)
    return digest.hexdigest()


def profile_dir(account_id: str) -> Path:
    return RUNTIME_HOME / "profiles" / profile_name(account_id)


def profile_base_url(root_url: str, account_id: str) -> str:
    return f"{root_url}/p/{profile_name(account_id)}"


def env_values(path: Path) -> dict[str, str]:
    """KEY=value lines of a runtime .env file; comments and blank lines are skipped."""
    values = {}
    if not path.is_file():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        name = name.strip().removeprefix("export ").strip()
        values[name] = value.strip()
    return values


def write_private(path: Path, content: str) -> None:
    """Replace a file atomically, readable only by its owner."""
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as file:
            file.write(content)
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def profile_env(account_id: str) -> str:
    lines = [
        "# Mula account profile. Generated by the backend; edits are overwritten on the next sync.",
        "API_SERVER_ENABLED=true",
        f"API_SERVER_KEY={profile_key(account_id)}",
    ]
    root = env_values(RUNTIME_HOME / ".env")
    for name in MIRRORED_SECRETS:
        if root.get(name):
            lines.append(f"{name}={root[name]}")
    lines.append(f"{MODEL_BASE_URL_NAME}={model_base_url(root)}")
    return "\n".join(lines) + "\n"


def model_base_url(root: dict[str, str] | None = None) -> str:
    """The model address for every profile; see MODEL_BASE_URL_NAME."""
    if root is None:
        root = env_values(RUNTIME_HOME / ".env")
    value = os.getenv(MODEL_BASE_URL_NAME, "").strip() or root.get(MODEL_BASE_URL_NAME, "").strip()
    return value or DEFAULT_MODEL_BASE_URL


def profile_config() -> str:
    config = TEMPLATE.read_text(encoding="utf-8")
    if "memory_enabled: false" not in config:
        raise ProfileError("The account profile template must keep the runtime's memory off.")
    return config


def ensure_profile(account_id: str) -> Path:
    """Create or refresh the account's profile. Safe to call on every turn."""
    folder = profile_dir(account_id)
    if folder.is_symlink():
        raise ProfileError("The runtime profile folder must not be a symbolic link.")
    # Derive everything before touching the disk: a missing seed or a bad template must not
    # leave a half-written profile (a folder with a config but no key) behind.
    config = profile_config()
    env = profile_env(account_id)
    identity = IDENTITY.read_text(encoding="utf-8")
    try:
        folder.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        folder.mkdir(exist_ok=True, mode=0o700)
        config_path = folder / "config.yaml"
        if not config_path.is_file() or config_path.read_text(encoding="utf-8") != config:
            write_private(config_path, config)
        env_path = folder / ".env"
        if not env_path.is_file() or env_path.read_text(encoding="utf-8") != env:
            write_private(env_path, env)
        identity_path = folder / "SOUL.md"
        if not identity_path.is_file() or identity_path.read_text(encoding="utf-8") != identity:
            write_private(identity_path, identity)
        marker = folder / NO_SKILLS_MARKER
        if not marker.exists():
            write_private(marker, "This Mula account profile does not use bundled skills.\n")
    except OSError as error:
        raise ProfileError("The account's runtime profile could not be written. Check the runtime folder's permissions.") from error
    return folder


def announce_profile(account_id: str) -> None:
    """Ask a running gateway to start serving the account's profile now instead of at its next rescan.

    Best effort: without a gateway there is nothing to tell, and the gateway serves every profile
    folder it finds when it starts.
    """
    runtime_control.rescan_profiles(RUNTIME_HOME)


def ensure_served(account_id: str) -> None:
    """Refuse a turn that the gateway would fail with `profile_mismatch`.

    A gateway serves a new profile folder only after a rescan. When a gateway answers and still does
    not serve the profile after SERVE_WAIT_SECONDS, the turn is refused with a message that says to
    retry. When no gateway answers, nothing is known, and the turn fails on its own connection error.
    """
    state = runtime_control.ensure_served(RUNTIME_HOME, profile_name(account_id), SERVE_WAIT_SECONDS)
    if state is False:
        raise ProfileError("Mula's runtime has not started serving this account yet. Try again in a moment.")


def profile_memory_is_off(folder: Path) -> bool:
    config_path = folder / "config.yaml"
    if not config_path.is_file():
        return False
    return "memory_enabled: false" in config_path.read_text(encoding="utf-8")


def existing_profiles() -> list[Path]:
    """Account profile folders on disk, whoever they belong to."""
    root = RUNTIME_HOME / "profiles"
    if not root.is_dir():
        return []
    return sorted(entry for entry in root.iterdir() if entry.is_dir() and entry.name.startswith("mula-") and PROFILE_ID.match(entry.name))


def profiles_with_runtime_memory() -> list[str]:
    return [folder.name for folder in existing_profiles() if not profile_memory_is_off(folder)]
